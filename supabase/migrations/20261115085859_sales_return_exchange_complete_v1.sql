-- Sales return exchange schema foundation
ALTER TABLE public.sales_returns DROP CONSTRAINT IF EXISTS sales_returns_return_type_check;
ALTER TABLE public.sales_returns ADD CONSTRAINT sales_returns_return_type_check CHECK (return_type IN ('RETURN','EXCHANGE'));
ALTER TABLE public.sales_returns DROP CONSTRAINT IF EXISTS sales_returns_cash_action_check;
ALTER TABLE public.sales_returns ADD CONSTRAINT sales_returns_cash_action_check CHECK (cash_action IS NULL OR cash_action IN ('NONE','CUSTOMER_PAYS_CASH','CUSTOMER_PAYS_CREDIT','DEDUCT_DEBT','CASH_BACK','CREDIT_BALANCE'));
ALTER TABLE public.sales_return_exchange_items ADD COLUMN IF NOT EXISTS request_id uuid;
ALTER TABLE public.sales_return_exchange_items ADD COLUMN IF NOT EXISTS lot_id bigint REFERENCES public.stock_lots(lot_id);
CREATE UNIQUE INDEX IF NOT EXISTS sales_return_exchange_items_request_id_uq ON public.sales_return_exchange_items(request_id) WHERE request_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS sales_return_exchange_items_return_id_idx ON public.sales_return_exchange_items(sales_return_id);
CREATE TABLE IF NOT EXISTS public.customer_credit_balances (
  customer_id bigint PRIMARY KEY REFERENCES public.customers(customer_id),
  balance numeric NOT NULL DEFAULT 0 CHECK (balance >= 0),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.customer_credit_transactions (
  transaction_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint NOT NULL REFERENCES public.customers(customer_id),
  sales_return_id bigint REFERENCES public.sales_returns(sales_return_id),
  direction text NOT NULL CHECK (direction IN ('CREDIT','DEBIT')),
  amount numeric NOT NULL CHECK (amount > 0),
  balance_after numeric NOT NULL CHECK (balance_after >= 0),
  notes text,
  created_by uuid REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.customer_credit_balances ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.customer_credit_transactions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.customer_credit_balances FROM anon, authenticated;
REVOKE ALL ON public.customer_credit_transactions FROM anon, authenticated;
GRANT SELECT ON public.customer_credit_balances TO authenticated;
GRANT SELECT ON public.customer_credit_transactions TO authenticated;
DROP POLICY IF EXISTS customer_credit_balances_read ON public.customer_credit_balances;
CREATE POLICY customer_credit_balances_read ON public.customer_credit_balances FOR SELECT TO authenticated USING (public.has_permission('REPORTS_VIEW') OR public.has_permission('CUSTOMERS_VIEW'));
DROP POLICY IF EXISTS customer_credit_transactions_read ON public.customer_credit_transactions;
CREATE POLICY customer_credit_transactions_read ON public.customer_credit_transactions FOR SELECT TO authenticated USING (public.has_permission('REPORTS_VIEW') OR public.has_permission('CUSTOMERS_VIEW'));