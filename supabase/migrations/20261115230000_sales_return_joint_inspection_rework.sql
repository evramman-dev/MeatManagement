CREATE OR REPLACE FUNCTION public.get_sales_return_rework_stock(p_location_id bigint DEFAULT NULL)
RETURNS TABLE(return_item_id bigint,product_id bigint,location_id bigint,available_quantity numeric,return_number text,received_at timestamptz)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
BEGIN
