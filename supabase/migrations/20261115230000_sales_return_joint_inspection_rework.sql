CREATE OR REPLACE FUNCTION public.track_return_rework_consumption()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE r record; c record; v_remaining numeric; v_take numeric;
BEGIN
 IF NEW.movement_type='ISSUE' AND NEW.quantity_change<0 AND NEW.production_order_id IS NOT NULL AND NEW.production_order_material_id IS NOT NULL AND NEW.reversal_of_movement_id IS NULL THEN
  v_remaining:=abs(NEW.quantity_change);
  FOR r IN SELECT * FROM public.reservations WHERE location_id=NEW.location_id AND product_id=NEW.product_id AND status='ACTIVE' AND notes LIKE 'RETURN_REWORK:%' ORDER BY created_at,reservation_id FOR UPDATE
  LOOP
   EXIT WHEN v_remaining<=0;
   v_take:=LEAST(v_remaining,r.quantity);
   INSERT INTO public.production_rework_consumptions(movement_id,return_item_id,reservation_id,production_order_id,location_id,product_id,quantity)
   VALUES(NEW.movement_id,r.source_return_item_id,r.reservation_id,NEW.production_order_id,NEW.location_id,NEW.product_id,v_take)
   ON CONFLICT(movement_id,return_item_id) DO NOTHING;
   IF v_take>=r.quantity THEN UPDATE public.reservations SET status='CANCELLED' WHERE reservation_id=r.reservation_id;
   ELSE UPDATE public.reservations SET quantity=quantity-v_take WHERE reservation_id=r.reservation_id; END IF;
   v_remaining:=v_remaining-v_take;
  END LOOP;
 ELSIF NEW.reversal_of_movement_id IS NOT NULL AND NEW.quantity_change>0 AND EXISTS(
  SELECT 1 FROM public.stock_movements sm WHERE sm.movement_id=NEW.reversal_of_movement_id AND sm.production_order_id IS NOT NULL AND sm.movement_type='ISSUE'
 ) THEN
  v_remaining:=NEW.quantity_change;
  FOR c IN SELECT * FROM public.production_rework_consumptions WHERE movement_id=NEW.reversal_of_movement_id AND reversed_quantity<quantity ORDER BY consumption_id FOR UPDATE
  LOOP
   EXIT WHEN v_remaining<=0;
   v_take:=LEAST(v_remaining,c.quantity-c.reversed_quantity);
   IF EXISTS(SELECT 1 FROM public.reservations rr WHERE rr.source_return_item_id=c.return_item_id AND rr.location_id=c.location_id AND rr.product_id=c.product_id AND rr.status='ACTIVE' AND rr.notes LIKE 'RETURN_REWORK:%') THEN
    UPDATE public.reservations SET quantity=quantity+v_take WHERE reservation_id=(
     SELECT rr.reservation_id FROM public.reservations rr WHERE rr.source_return_item_id=c.return_item_id AND rr.location_id=c.location_id AND rr.product_id=c.product_id AND rr.status='ACTIVE' AND rr.notes LIKE 'RETURN_REWORK:%' ORDER BY rr.reservation_id LIMIT 1
    );
   ELSE
    INSERT INTO public.reservations(customer_id,product_id,location_id,quantity,reserved_until,notes,status,created_by,request_id,source_return_item_id)
    VALUES(NULL,c.product_id,c.location_id,v_take,NULL,'RETURN_REWORK:'||c.return_item_id,'ACTIVE',NEW.created_by,gen_random_uuid(),c.return_item_id);
   END IF;
   UPDATE public.production_rework_consumptions SET reversed_quantity=reversed_quantity+v_take WHERE consumption_id=c.consumption_id;
   v_remaining:=v_remaining-v_take;
  END LOOP;
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_stock_movement_return_rework_consumption ON public.stock_movements;
CREATE TRIGGER trg_stock_movement_return_rework_consumption AFTER INSERT ON public.stock_movements FOR EACH ROW
EXECUTE FUNCTION public.track_return_rework_consumption();

