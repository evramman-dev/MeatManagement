CREATE FUNCTION public.create_stock_transfer(p_source_location_id bigint,p_destination_location_id bigint,p_transfer_date date,p_items jsonb,p_notes text,p_request_id uuid)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_destination_type text; v_transfer_id bigint; v_item record; v_res public.reservations%ROWTYPE; v_remaining numeric; v_take numeric; v_prefix text; v_prefixes text[];
BEGIN
 SELECT location_type INTO v_destination_type FROM public.locations WHERE location_id=p_destination_location_id AND is_active;
 IF NOT FOUND THEN RAISE EXCEPTION 'موقع الوجهة غير نشط أو غير موجود'; END IF;
 IF v_destination_type IN('FRIDGE','MAIN_WAREHOUSE') THEN
  PERFORM set_config('app.allow_return_pending_reservations','on',true);
  PERFORM set_config('app.allow_return_rework_reservations','on',true);
  v_prefixes:=ARRAY['RETURN_PENDING:%','RETURN_REWORK:%'];
 ELSIF v_destination_type='FACTORY' THEN
  PERFORM set_config('app.allow_return_rework_reservations','on',true);
  v_prefixes:=ARRAY['RETURN_REWORK:%'];
 ELSE v_prefixes:=ARRAY[]::text[]; END IF;
 v_transfer_id:=public.create_stock_transfer_internal_return_rework(p_source_location_id,p_destination_location_id,p_transfer_date,p_items,p_notes,p_request_id);
 FOREACH v_prefix IN ARRAY v_prefixes LOOP
  FOR v_item IN SELECT (e->>'product_id')::bigint product_id,SUM((e->>'quantity')::numeric) quantity FROM jsonb_array_elements(p_items) e GROUP BY (e->>'product_id')::bigint
  LOOP
   v_remaining:=v_item.quantity;
   FOR v_res IN SELECT * FROM public.reservations WHERE location_id=p_source_location_id AND product_id=v_item.product_id AND status='ACTIVE' AND notes LIKE v_prefix ORDER BY created_at,reservation_id FOR UPDATE
   LOOP
    EXIT WHEN v_remaining<=0;
    v_take:=LEAST(v_remaining,v_res.quantity);
    IF v_prefix='RETURN_PENDING:%' AND v_take<v_res.quantity THEN RAISE EXCEPTION 'يجب نقل كامل كمية المرتجع المحجوزة إلى الثلاجة في عملية واحدة'; END IF;
    IF v_take>=v_res.quantity THEN
     UPDATE public.reservations SET location_id=p_destination_location_id WHERE reservation_id=v_res.reservation_id;
    ELSE
     UPDATE public.reservations SET quantity=quantity-v_take WHERE reservation_id=v_res.reservation_id;
     INSERT INTO public.reservations(customer_id,product_id,location_id,quantity,reserved_until,notes,status,created_by,request_id,source_return_item_id)
     VALUES(v_res.customer_id,v_res.product_id,p_destination_location_id,v_take,v_res.reserved_until,v_res.notes,'ACTIVE',auth.uid(),gen_random_uuid(),v_res.source_return_item_id);
    END IF;
    v_remaining:=v_remaining-v_take;
   END LOOP;
  END LOOP;
 END LOOP;
 IF v_destination_type IN('FRIDGE','MAIN_WAREHOUSE') THEN
  UPDATE public.sales_return_item_inspections i SET received_location_id=p_destination_location_id,received_at=COALESCE(i.received_at,now()),updated_at=now()
  WHERE i.return_item_id IN(SELECT r.source_return_item_id FROM public.reservations r WHERE r.location_id=p_destination_location_id AND r.status='ACTIVE' AND r.notes LIKE 'RETURN_PENDING:%');
 END IF;
 RETURN v_transfer_id;
END $$;
GRANT EXECUTE ON FUNCTION public.create_stock_transfer(bigint,bigint,date,jsonb,text,uuid) TO authenticated;

