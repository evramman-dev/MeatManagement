  UPDATE public.reservations SET status='CANCELLED'
  WHERE source_return_item_id IN(SELECT return_item_id FROM public.sales_return_items WHERE sales_return_id=NEW.sales_return_id) AND status='ACTIVE';
  UPDATE public.sales_return_item_inspections SET inspection_status='CANCELLED',updated_at=now()
