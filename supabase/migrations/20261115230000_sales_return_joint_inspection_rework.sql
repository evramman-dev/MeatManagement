CREATE OR REPLACE FUNCTION public.add_production_order_extra_material(p_order_id bigint,p_product_id bigint,p_quantity numeric,p_request_id uuid)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_order public.production_orders%ROWTYPE; v_product public.products%ROWTYPE; v_existing public.production_order_materials%ROWTYPE; v_material_id bigint;
BEGIN
 IF auth.uid() IS NULL OR NOT public.has_permission('PRODUCTION_MANAGE') THEN RAISE EXCEPTION 'لا تملك صلاحية إضافة مكون لأمر الإنتاج'; END IF;
 IF p_quantity IS NULL OR p_quantity<=0 OR p_request_id IS NULL THEN RAISE EXCEPTION 'الكمية ومعرف الطلب مطلوبان'; END IF;
 SELECT * INTO v_order FROM public.production_orders WHERE order_id=p_order_id FOR UPDATE;
 IF NOT FOUND OR v_order.status<>'DRAFT' THEN RAISE EXCEPTION 'يمكن إضافة مكونات إضافية إلى أمر إنتاج مسودة فقط'; END IF;
 SELECT * INTO v_product FROM public.products WHERE product_id=p_product_id AND is_active;
 IF NOT FOUND OR v_product.product_type NOT IN('RAW','SEMI_FINISHED','FINISHED') THEN RAISE EXCEPTION 'المنتج غير نشط أو نوعه غير مسموح كمكون إنتاج'; END IF;
 SELECT * INTO v_existing FROM public.production_order_materials WHERE request_id=p_request_id;
 IF FOUND THEN
  IF v_existing.order_id<>p_order_id OR v_existing.raw_product_id<>p_product_id OR v_existing.required_quantity<>p_quantity THEN RAISE EXCEPTION 'معرف الطلب مستخدم لبيانات مختلفة'; END IF;
  RETURN v_existing.material_id;
 END IF;
 PERFORM set_config('app.allow_return_rework_reservations','on',true);
 PERFORM public.assert_stock_available(v_order.factory_location_id,p_product_id,p_quantity);
 INSERT INTO public.production_order_materials(order_id,raw_product_id,required_quantity,unit_id,is_extra,request_id)
 VALUES(p_order_id,p_product_id,p_quantity,v_product.base_unit_id,true,p_request_id)
 RETURNING material_id INTO v_material_id;
 RETURN v_material_id;
END $$;
