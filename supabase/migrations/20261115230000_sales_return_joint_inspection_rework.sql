 RETURN QUERY
 SELECT r.source_return_item_id,sri.product_id,r.location_id,SUM(r.quantity)::numeric,sr.return_number,i.received_at
 FROM public.reservations r JOIN public.sales_return_items sri ON sri.return_item_id=r.source_return_item_id
 JOIN public.sales_returns sr ON sr.sales_return_id=sri.sales_return_id
 JOIN public.sales_return_item_inspections i ON i.return_item_id=sri.return_item_id
 WHERE r.status='ACTIVE' AND r.notes LIKE 'RETURN_REWORK:%' AND (p_location_id IS NULL OR r.location_id=p_location_id)
 GROUP BY r.source_return_item_id,sri.product_id,r.location_id,sr.return_number,i.received_at
 ORDER BY sr.return_number,r.source_return_item_id;
END $$;
