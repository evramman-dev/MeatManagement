-- MeatManagement Lot Traceability schema snapshot
-- Applied on 2026-11-11. This is an audit record, not a reset script.

CREATE SEQUENCE IF NOT EXISTS public.stock_lot_code_seq;

CREATE TABLE IF NOT EXISTS public.stock_lots (
  lot_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lot_code text NOT NULL UNIQUE DEFAULT (
    'LOT-' || to_char(CURRENT_DATE,'YYYYMMDD') || '-' ||
    lpad(nextval('public.stock_lot_code_seq')::text,6,'0')
  ),
  product_id bigint NOT NULL REFERENCES public.products(product_id),
  source_type text NOT NULL CHECK (source_type IN ('PURCHASE','PRODUCTION','OPENING','RETURN','ADJUSTMENT','OTHER')),
  source_purchase_invoice_item_id bigint UNIQUE REFERENCES public.purchase_invoice_items(item_id),
  source_production_order_id bigint REFERENCES public.production_orders(order_id),
  supplier_id bigint REFERENCES public.suppliers(supplier_id),
  supplier_lot_code text,
  manufactured_on date,
  expires_on date,
  received_at timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','QUARANTINE','EXPIRED','CLOSED')),
  notes text,
  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT stock_lots_dates_valid CHECK (expires_on IS NULL OR manufactured_on IS NULL OR expires_on >= manufactured_on),
  CONSTRAINT stock_lots_source_purchase_type CHECK (source_purchase_invoice_item_id IS NULL OR source_type='PURCHASE'),
  CONSTRAINT stock_lots_source_production_type CHECK (source_production_order_id IS NULL OR source_type='PRODUCTION')
);

CREATE UNIQUE INDEX IF NOT EXISTS stock_lots_production_order_unique
ON public.stock_lots(source_production_order_id)
WHERE source_production_order_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS stock_lots_product_expiry_idx
ON public.stock_lots(product_id,status,expires_on,received_at);

CREATE TABLE IF NOT EXISTS public.stock_lot_balances (
  lot_balance_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lot_id bigint NOT NULL REFERENCES public.stock_lots(lot_id),
  location_id bigint NOT NULL REFERENCES public.locations(location_id),
  quantity numeric(20,4) NOT NULL DEFAULT 0 CHECK (quantity>=0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(lot_id,location_id)
);

CREATE INDEX IF NOT EXISTS stock_lot_balances_location_lot_idx
ON public.stock_lot_balances(location_id,lot_id);

CREATE TABLE IF NOT EXISTS public.stock_movement_lot_allocations (
  allocation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  movement_id bigint NOT NULL REFERENCES public.stock_movements(movement_id) ON DELETE RESTRICT,
  lot_id bigint NOT NULL REFERENCES public.stock_lots(lot_id),
  allocation_direction text NOT NULL CHECK (allocation_direction IN ('IN','OUT')),
  quantity numeric(20,4) NOT NULL CHECK (quantity>0),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(movement_id,lot_id,allocation_direction)
);

CREATE INDEX IF NOT EXISTS stock_movement_lot_allocations_lot_idx
ON public.stock_movement_lot_allocations(lot_id,movement_id);

ALTER TABLE public.purchase_invoice_items
  ADD COLUMN IF NOT EXISTS supplier_lot_code text,
  ADD COLUMN IF NOT EXISTS manufactured_on date,
  ADD COLUMN IF NOT EXISTS expires_on date;

ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS shelf_life_days integer
  CHECK (shelf_life_days IS NULL OR shelf_life_days>0);

ALTER TABLE public.production_orders
  ADD COLUMN IF NOT EXISTS output_lot_id bigint REFERENCES public.stock_lots(lot_id);

ALTER TABLE public.stock_movements
  ADD COLUMN IF NOT EXISTS sales_invoice_id bigint REFERENCES public.sales_invoices(sales_invoice_id),
  ADD COLUMN IF NOT EXISTS sales_invoice_item_id bigint REFERENCES public.sales_invoice_items(sales_invoice_item_id),
  ADD COLUMN IF NOT EXISTS sales_return_id bigint REFERENCES public.sales_returns(sales_return_id),
  ADD COLUMN IF NOT EXISTS sales_return_item_id bigint REFERENCES public.sales_return_items(return_item_id);

ALTER TABLE public.sales_invoice_items
  ADD CONSTRAINT sales_invoice_items_lot_fk
  FOREIGN KEY (lot_id) REFERENCES public.stock_lots(lot_id);

ALTER TABLE public.sales_return_items
  ADD CONSTRAINT sales_return_items_lot_fk
  FOREIGN KEY (lot_id) REFERENCES public.stock_lots(lot_id);

CREATE INDEX IF NOT EXISTS stock_movements_sales_invoice_item_idx
ON public.stock_movements(sales_invoice_id,sales_invoice_item_id)
WHERE sales_invoice_id IS NOT NULL;

ALTER TABLE public.stock_lots ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stock_lot_balances ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stock_movement_lot_allocations ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS stock_lots_select_access ON public.stock_lots;
CREATE POLICY stock_lots_select_access ON public.stock_lots
FOR SELECT TO authenticated
USING (
  public.has_permission('STOCK_VIEW')
  OR public.has_permission('INVENTORY_VIEW')
  OR public.has_permission('STOCK_MANAGE')
  OR public.has_permission('PURCHASES_VIEW')
  OR public.has_permission('PRODUCTION_VIEW')
  OR public.has_permission('PRODUCTION_MANAGE')
);

DROP POLICY IF EXISTS stock_lot_balances_select_access ON public.stock_lot_balances;
CREATE POLICY stock_lot_balances_select_access ON public.stock_lot_balances
FOR SELECT TO authenticated
USING (
  public.has_permission('STOCK_VIEW')
  OR public.has_permission('INVENTORY_VIEW')
  OR public.has_permission('STOCK_MANAGE')
);

DROP POLICY IF EXISTS stock_movement_lot_allocations_select_access ON public.stock_movement_lot_allocations;
CREATE POLICY stock_movement_lot_allocations_select_access ON public.stock_movement_lot_allocations
FOR SELECT TO authenticated
USING (
  public.has_permission('STOCK_VIEW')
  OR public.has_permission('INVENTORY_VIEW')
  OR public.has_permission('STOCK_MANAGE')
);

GRANT SELECT ON public.stock_lots,public.stock_lot_balances,public.stock_movement_lot_allocations TO authenticated;
GRANT USAGE,SELECT ON SEQUENCE public.stock_lots_lot_id_seq,public.stock_lot_balances_lot_balance_id_seq,public.stock_movement_lot_allocations_allocation_id_seq TO authenticated;

